// Writes the tool reference of docs/MCP.md (below the marker) from the running server, so that it is exact.
// Run after `npm run build`:   npm run docs:mcp
import { readFileSync, writeFileSync } from 'node:fs';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';
import { createServer } from '../packages/mcp/dist/index.js';

const path = new URL('../docs/MCP.md', import.meta.url);
const marker = '<!-- generated by scripts/generate-mcp-docs.mjs: do not edit below this line -->';

const server = createServer({ env: {} });
const [clientSide, serverSide] = InMemoryTransport.createLinkedPair();
await server.connect(serverSide);
const client = new Client({ name: 'docs', version: '1.0.0' });
await client.connect(clientSide);
const { tools } = await client.listTools();

function typeOf(schema) {
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(' | ');
  if (schema.anyOf) return schema.anyOf.map(typeOf).join(' | ');
  if (schema.type === 'array') return `${schema.items ? typeOf(schema.items) : 'any'}[]`;
  if (schema.type === 'object' && schema.properties) return '{ ' + Object.keys(schema.properties).join(', ') + ' }';
  return schema.type ?? 'any';
}

const lines = ['## Tool reference', '', `${tools.length} tools. Arguments marked * are required. Every tool that works on a project also takes an optional \`project\` (the path of the project file; default: the project created or opened earlier in the session).`, ''];
for (const tool of tools) {
  const flags = [tool.annotations?.readOnlyHint ? 'read-only' : '', tool.annotations?.destructiveHint ? 'destructive' : ''].filter(Boolean).join(', ');
  lines.push(`### \`${tool.name}\`${flags ? ` (${flags})` : ''}`, '', tool.description ?? '', '');
  const properties = tool.inputSchema.properties ?? {};
  const required = new Set(tool.inputSchema.required ?? []);
  const rows = Object.entries(properties).filter(([name]) => name !== 'project');
  if (rows.length > 0) {
    lines.push('Arguments:', '');
    for (const [name, schema] of rows) lines.push(`- \`${name}\`${required.has(name) ? '*' : ''} (${typeOf(schema)})${schema.description ? `: ${schema.description}` : ''}`);
    lines.push('');
  }
}
await client.close();

const existing = readFileSync(path, 'utf8');
const head = existing.includes(marker) ? existing.slice(0, existing.indexOf(marker)) : `${existing}\n`;
writeFileSync(path, `${head}${marker}\n\n${lines.join('\n')}`);
console.log(`wrote the reference of ${tools.length} tools to docs/MCP.md`);
